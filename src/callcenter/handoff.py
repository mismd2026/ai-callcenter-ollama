"""Handoff summary for the human operator.

When a call is escalated to Layer 3 the operator should not have to ask the
caller to start over. This module turns the conversation history into a short
brief: what the caller wants, why the AI handed off, and the exchange so far.

The summary is generated by the same self-hosted LLM, but it must never block
the handoff itself: the API builds it after the caller's reply is sent, and if
the LLM fails a deterministic fallback is used instead.
"""

from __future__ import annotations

import logging
import re
from dataclasses import dataclass, field

from .adapters import ChatModel

log = logging.getLogger(__name__)

SUMMARY_PROMPT = """あなたはコールセンターの引き継ぎメモを書く担当です。
以下の通話記録を読み、オペレーターが最初に把握すべきお客様の用件を、1〜2文の日本語で要約してください。
- 推測は書かず、記録に書かれていることだけをまとめてください。
- カード番号・口座番号・パスワードなどの個人情報は要約に含めないでください。
- 前置きや見出しは付けず、要約の文だけを出力してください。
"""

# 8+ consecutive digits (allowing spaces/hyphens) look like card / account numbers.
_LONG_NUMBER = re.compile(r"\d(?:[\s-]?\d){7,}")


def mask_numbers(text: str) -> str:
    """Hide long digit runs so they never reach the operator screen or logs."""
    return _LONG_NUMBER.sub("[番号は非表示]", text)


@dataclass
class HandoffSummary:
    summary: str
    reason: str
    last_utterance: str
    transcript: list[dict[str, str]] = field(default_factory=list)
    faq_sources: list[str] = field(default_factory=list)
    generated_by: str = "llm"  # "llm" | "fallback"


@dataclass
class HandoffSummarizer:
    llm: ChatModel
    max_chars: int = 200

    def summarize(
        self,
        history: list[tuple[str, str]],
        reason: str,
        faq_sources: list[str] | None = None,
    ) -> HandoffSummary:
        transcript = [
            {"role": role, "text": mask_numbers(text)}
            for caller, reply in history
            for role, text in (("caller", caller), ("ai", reply))
        ]
        last = mask_numbers(history[-1][0]) if history else ""
        base = dict(
            reason=reason,
            last_utterance=last,
            transcript=transcript,
            faq_sources=list(dict.fromkeys(faq_sources or [])),
        )

        record = "\n".join(
            f"{'お客様' if t['role'] == 'caller' else 'AI'}: {t['text']}" for t in transcript
        )
        try:
            text = self.llm.chat(
                [
                    {"role": "system", "content": SUMMARY_PROMPT},
                    {"role": "user", "content": f"通話記録:\n{record}"},
                ],
                temperature=0,
            )
        except Exception:  # summary is best-effort; the handoff must still happen
            log.exception("handoff summary generation failed")
            text = ""

        text = mask_numbers(text.strip())
        if not text:
            return HandoffSummary(summary=f"お客様の発話: {last}", generated_by="fallback", **base)
        return HandoffSummary(summary=text[: self.max_chars], **base)
